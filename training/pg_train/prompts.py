"""Option sets + prompt rendering. Source of truth is Swift (core/Sources/PocketCore/Decision.swift);
config/option_sets.json is generated by `pg-cli dump-sets` and tests/test_parity.py keeps them in sync."""
import json
from pathlib import Path

LETTERS = "ABCDEFGH"
_CFG = json.loads((Path(__file__).resolve().parent.parent / "config" / "option_sets.json").read_text())
SYSTEM = _CFG["system"]
SETS = {s["type"]: s for s in _CFG["sets"] if s["type"] not in ("contactPick", "eventPick")}


def dynamic_set(kind: str, candidates: list[str]) -> dict:
    assert kind in ("contactPick", "eventPick")
    c = candidates[:7]
    q = "Which contact does the user mean?" if kind == "contactPick" else "Which calendar event does the user mean?"
    p = "c" if kind == "contactPick" else "e"
    return {"type": kind, "question": q, "fallback": "ask",
            "options": [{"id": f"{p}{i}", "label": x} for i, x in enumerate(c)] + [{"id": "ask", "label": "Unclear: ask the user"}]}


def get_set(kind: str, candidates: list[str] | None = None) -> dict:
    return dynamic_set(kind, candidates or []) if kind in ("contactPick", "eventPick") else SETS[kind]


def body(s: dict, context: str) -> str:
    out = f"Context:\n{context.strip()}\n\nQuestion: {s['question']}\n"
    for i, o in enumerate(s["options"]):
        out += f"{LETTERS[i]}. {o['label']}\n"
    return out + "Answer with one letter."


def llama3(s: dict, context: str) -> str:
    return ("<|begin_of_text|><|start_header_id|>system<|end_header_id|>\n\n" + SYSTEM + "<|eot_id|>"
            "<|start_header_id|>user<|end_header_id|>\n\n" + body(s, context) + "<|eot_id|>"
            "<|start_header_id|>assistant<|end_header_id|>\n\nAnswer:")


def chat_messages(s: dict, context: str) -> list[dict]:
    """For chat-API teachers (Muse Spark Open / Glimmer): same content, provider applies its own template."""
    return [{"role": "system", "content": SYSTEM}, {"role": "user", "content": body(s, context)}]


def letters(s: dict) -> list[str]:
    return list(LETTERS[: len(s["options"])])
